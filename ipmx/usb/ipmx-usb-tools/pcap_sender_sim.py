# ---------------------------------------------------------------------------
# PEP encryption state for the simulator (Sender role)
# ---------------------------------------------------------------------------

class SimPepState:
    """Manages PEP encrypt/decrypt for one direction of one channel.

    The Sender sim:
      - Encrypts its outgoing messages with the S2R key (even SSID).
      - Decrypts incoming Receiver messages with the R2S key (odd SSID).

    Handshake SSID: first message pair on each data channel uses SSID 2/3,
    then switches to the payload SSID from USBStreamInfo.
    """

    def __init__(self, psk: bytes, mode: PepMode = PepMode.AES_128_CTR_CMAC_64_AAD,
                 sender_kv: int = 1, corrupt_nth: int = 0,
                 base_iv: int = 0, key_generator: bytes = b'\x00' * 16):
        self.psk = psk
        self.mode = mode
        self.sender_kv = sender_kv
        self.receiver_kv = 0

        self.key_generator = key_generator
        kv_bytes = sender_kv.to_bytes(4, 'big')
        self.s2r_key = derive_privacy_key(
            psk, self.key_generator, kv_bytes, key_bits=128)
        self.r2s_key = b'\x00' * 16  # derived after we learn receiver_kv

        self.base_iv: int = base_iv
        self.ctr_s2r: int = 0
        self.ctr_r2s: int = 0
        self.handshake_done = False
        self.payload_ssid: int = 0
        self.corrupt_nth: int = corrupt_nth
        self._s2r_msg_count: int = 0

    def derive_r2s_key(self, receiver_kv: int) -> None:
        self.receiver_kv = receiver_kv
        kv_bytes = receiver_kv.to_bytes(4, 'big')
        self.r2s_key = derive_privacy_key(
            self.psk, self.key_generator, kv_bytes, key_bits=128)

    def encrypt_s2r(self, raw: bytes) -> bytes:
        """Encrypt an outgoing Sender message (S2R direction).

        Patches CTR and KEYVERSION into the header before encrypting.
        """
        ssid = self.payload_ssid if self.handshake_done else 2
        iv_prime = compute_iv_prime(self.base_iv, ssid)

        hdr = bytearray(raw[:16])
        struct.pack_into('>Q', hdr, 0, self.ctr_s2r)
        struct.pack_into('>I', hdr, 8, self.sender_kv)
        patched = bytes(hdr) + raw[16:]

        enc = encrypt_usb_message(patched, self.s2r_key, iv_prime, self.mode)
        self.ctr_s2r += usb_ctr_advance(len(enc))
        self._s2r_msg_count += 1
        if (self.corrupt_nth > 0 and self.handshake_done and
                self._s2r_msg_count % self.corrupt_nth == 0):
            ba = bytearray(enc)
            ba[-1] ^= 0xFF
            enc = bytes(ba)
            print(f"  [sim pep] INJECTED MAC corruption on S2R msg #{self._s2r_msg_count}")
        return enc

    def decrypt_r2s(self, raw: bytes) -> bytes:
        """Decrypt an incoming Receiver message (R2S direction).

        On the first R2S message, reads key_version from the clear-text header
        and derives the R2S key dynamically (the Receiver picks a random kv).
        """
        if len(raw) >= 12 and self.receiver_kv == 0:
            incoming_kv = struct.unpack('>I', raw[8:12])[0]
            if incoming_kv != 0:
                self.derive_r2s_key(incoming_kv)
                print(f"  [sim pep] derived R2S key from receiver_kv={incoming_kv:#010x}")

        ssid = (self.payload_ssid | 1) if self.handshake_done else 3
        iv_prime = compute_iv_prime(self.base_iv, ssid)
        dec, mac_ok = decrypt_usb_message(raw, self.r2s_key, iv_prime, self.mode)
        self.ctr_r2s += usb_ctr_advance(len(raw))
        if not mac_ok:
            print(f"  [sim pep] WARNING: R2S MAC verification failed")
        return dec

    def finish_handshake(self, payload_ssid: int) -> None:
        self.payload_ssid = payload_ssid
        self.handshake_done = True


# ---------------------------------------------------------------------------
# Socket helpers
# ---------------------------------------------------------------------------

def _sendall(sock: socket.socket, data: bytes) -> None:
    try:
        sock.sendall(data)
    except OSError:
        pass


# Sentinel returned by _recv_msg when the peer closed the connection
# (as opposed to None which means the timeout expired with no message).
_DISCONNECTED = object()


def _recv_msg(sock: socket.socket, buf: bytearray,
              timeout: float = 10.0):
    """Block until one complete IPMX message is in *buf*, then parse it.

    Returns:
        IpmxUsbMessage  — a complete message was received.
        None            — timeout expired with no complete message.
        _DISCONNECTED   — the peer closed or reset the connection.
    """
    deadline = time.monotonic() + timeout
    while True:
        if len(buf) >= usb.HEADER_SIZE:
            length = usb.peek_length(bytes(buf))
            if length is not None and len(buf) >= length:
                raw = bytes(buf[:length])
                del buf[:length]
                return usb.parse_one(raw)
        remaining = deadline - time.monotonic()
        if remaining <= 0:
            return None
        sock.settimeout(min(1.0, remaining))
        try:
            chunk = sock.recv(65536)
        except socket.timeout:
            continue
        except OSError:
            return _DISCONNECTED
        if not chunk:          # TCP FIN — peer closed cleanly
            return _DISCONNECTED
        buf.extend(chunk)


