class SimSession:
    """
    Extracts Sender-side messages from a parsed IPMX PCAP session and
    organises them for replay.
    """

    def __init__(self, session: Session):
        self.session = session

        # Control channel: raw bytes of each Sender message, in order
        self.ctrl_msgs: list[bytes] = [
            cm.msg.raw for cm in session.control.messages
            if cm.src_ip == session.sender_ip
        ]

        # SenderConnectionInfo (first Sender control message)
        self.sci_raw: bytes = self.ctrl_msgs[0] if self.ctrl_msgs else b''

        # Heartbeat messages
        self.heartbeat_raw: bytes = usb.build_heartbeat()

        # Data channels: per substreamid maps
        # ctrl_returns[substreamid][seqnum] → raw SUBMIT_RETURN bytes
        # int_returns[substreamid]          → deque of raw INTERRUPT_SUBMIT_RETURN bytes
        # idle_int_return[substreamid]      → raw idle (all-zero) report Return
        self.ctrl_returns:    dict[int, dict[int, bytes]] = {}
        self.int_returns:     dict[int, deque] = {}
        self.bulk_returns:    dict[int, dict[int, bytes]] = {}
        self.iso_returns:     dict[int, dict[int, deque]] = {}
        self.stream_info_raw: dict[int, bytes] = {}

        for substreamid, ch in session.data_channels.items():
            self.stream_info_raw[substreamid] = b''
            self.ctrl_returns[substreamid]    = {}
            self.int_returns[substreamid]     = deque()
            self.bulk_returns[substreamid]    = {}
            self.iso_returns[substreamid]     = {}

            for cm in ch.messages:
                msg = cm.msg
                mt  = msg.msg_type_enum
                # After dissector decryption, is_encrypted is still True
                # (CTR/KV preserved) but payload fields are accessible.
                # Use the _encrypted sentinel to detect truly opaque messages.
                opaque = '_encrypted' in msg.payload

                if mt == MsgType.USB_STREAM_INFO:
                    self.stream_info_raw[substreamid] = msg.raw

                elif mt == MsgType.USB_CONTROL_SUBMIT_RETURN:
                    seqnum = msg.payload.get('seqnum', -1) if not opaque else -1
                    if seqnum >= 0:
                        self.ctrl_returns[substreamid][seqnum] = msg.raw

                elif mt == MsgType.USB_INTERRUPT_SUBMIT_RETURN:
                    self.int_returns[substreamid].append(msg.raw)

                elif mt == MsgType.USB_BULK_SUBMIT_RETURN:
                    seqnum = msg.payload.get('seqnum', -1) if not opaque else -1
                    if seqnum >= 0:
                        self.bulk_returns[substreamid][seqnum] = msg.raw

                elif mt == MsgType.USB_ISOCHRONOUS_SUBMIT_RETURN:
                    ep = msg.payload.get('endpoint', 0) if not opaque else 0
                    if ep not in self.iso_returns[substreamid]:
                        self.iso_returns[substreamid][ep] = deque()
                    self.iso_returns[substreamid][ep].append(msg.raw)

        print(f"  Loaded session: {len(session.data_channels)} data channel(s)")
        for sid, ch in session.data_channels.items():
            n_ctrl = len(self.ctrl_returns.get(sid, {}))
            n_int  = len(self.int_returns.get(sid, deque()))
            iso_ep_map = self.iso_returns.get(sid, {})
            n_iso = sum(len(q) for q in iso_ep_map.values())
            ep_detail = ", ".join(f"EP{e:#04x}={len(q)}" for e, q in sorted(iso_ep_map.items()))
            print(f"    SubstreamID=0x{sid:02X}: {n_ctrl} control returns, "
                  f"{n_int} interrupt returns, {n_iso} iso returns ({ep_detail})")


