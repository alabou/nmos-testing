# Data channel handler (Sender side)
# ---------------------------------------------------------------------------

class DataChannelSender:
    """
    Connects to the Receiver's data port and replays one USB device's
    data stream from the PCAP.
    """

    def __init__(self, sim: SimSession, substreamid: int,
                 receiver_ip: str, receiver_data_port: int,
                 stop_event: threading.Event,
                 pep_state: Optional[SimPepState] = None):
        self._sim        = sim
        self._sid        = substreamid
        self._rip        = receiver_ip
        self._rport      = receiver_data_port
        self._stop       = stop_event
        self._pep        = pep_state

    def run(self) -> None:
        sid = self._sid
        time.sleep(0.05)   # brief pause before connecting

        try:
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.connect((self._rip, self._rport))
        except OSError as exc:
            print(f"  [sim data {sid:#04x}] connect failed: {exc}")
            return

        buf = bytearray()
        print(f"  [sim data {sid:#04x}] connected to Receiver {self._rip}:{self._rport}")

        # PEP helpers: wrap send/recv with encryption/decryption
        def pep_send(s: socket.socket, data: bytes) -> None:
            if self._pep:
                data = self._pep.encrypt_s2r(data)
            _sendall(s, data)

        def pep_recv(s: socket.socket, b: bytearray,
                     timeout: float = 10.0):
            msg = _recv_msg(s, b, timeout=timeout)
            if msg is _DISCONNECTED or msg is None:
                return msg
            if self._pep and msg.raw:
                dec = bytearray(self._pep.decrypt_r2s(msg.raw))
                dec[0:12] = b'\x00' * 12  # clear CTR/KV so parse_one decodes payload
                return usb.parse_one(bytes(dec))
            return msg

        # Send USBStreamInfo
        si_raw = self._sim.stream_info_raw.get(sid, b'')
        if not si_raw:
            print(f"  [sim data {sid:#04x}] no USBStreamInfo in PCAP — skipping")
            sock.close()
            return
        pep_send(sock, si_raw)
        print(f"  [sim data {sid:#04x}] sent USBStreamInfo (encrypted={self._pep is not None})")

        # Wait for USBStreamStatus
        msg = pep_recv(sock, buf, timeout=10.0)
        if msg is _DISCONNECTED:
            print(f"  [sim data {sid:#04x}] Receiver disconnected before USBStreamStatus")
            sock.close()
            return
        if msg is None or msg.msg_type_enum != MsgType.USB_STREAM_STATUS:
            print(f"  [sim data {sid:#04x}] expected USBStreamStatus, "
                  f"got {msg.msg_type_name if msg else 'None'}")
            sock.close()
            return
        print(f"  [sim data {sid:#04x}] received USBStreamStatus — stream active")

        # Switch from handshake SSID (2/3) to payload SSID
        if self._pep:
            self._pep.finish_handshake(sid)
            print(f"  [sim data {sid:#04x}] PEP handshake done, payload SSID={sid}")

        ctrl_returns  = self._sim.ctrl_returns.get(sid, {})
        ctrl_return_queue = deque(
            v for _, v in sorted(ctrl_returns.items())
        )
        int_returns   = deque(self._sim.int_returns.get(sid, deque()))
        bulk_returns  = self._sim.bulk_returns.get(sid, {})
        iso_ep_map: dict[int, deque] = {
            ep: deque(q) for ep, q in self._sim.iso_returns.get(sid, {}).items()
        }

        # Fallback idle interrupt return (all-zero HID report, seqnum patched)
        idle_report   = b'\x00' * 8

        # Track the next expected control seqnum for proper pairing
        _RETURN_TYPES = {
            MsgType.USB_CONTROL_SUBMIT,
            MsgType.USB_BULK_SUBMIT,
            MsgType.USB_INTERRUPT_SUBMIT,
            MsgType.USB_ISOCHRONOUS_SUBMIT,
            MsgType.USB_CANCEL_SUBMIT,
        }

        while not self._stop.is_set():
            msg = pep_recv(sock, buf, timeout=2.0)
            if msg is _DISCONNECTED:
                print(f"  [sim data {sid:#04x}] Receiver disconnected")
                break
            if msg is None:
                continue

            mt = msg.msg_type_enum
            if mt not in _RETURN_TYPES:
                continue

            seqnum = msg.payload.get('seqnum', -1) if not msg.is_encrypted else -1
            ep     = msg.payload.get('endpoint', 0) if not msg.is_encrypted else 0
            dirn   = msg.payload.get('direction', 0) if not msg.is_encrypted else 0

            if mt == MsgType.USB_CONTROL_SUBMIT:
                ret_raw = ctrl_return_queue.popleft() if ctrl_return_queue else None
                if ret_raw:
                    pcap_ret = usb.parse_one(ret_raw)
                    pcap_dirn = pcap_ret.payload.get('direction', dirn) if not pcap_ret.is_encrypted else dirn
                    if pcap_dirn != dirn:
                        pep_send(sock, usb.build_usb_control_submit_return(
                            seqnum, ep, dirn, 0, 0,
                        ))
                    else:
                        pcap_seq = pcap_ret.payload.get('seqnum', seqnum)
                        patched = _patch_seqnum(ret_raw, seqnum) if pcap_seq != seqnum else ret_raw
                        pep_send(sock, patched)
                else:
                    pep_send(sock, usb.build_usb_control_submit_return(
                        seqnum, ep, dirn, 0, 0,
                    ))

            elif mt == MsgType.USB_INTERRUPT_SUBMIT:
                if int_returns:
                    ret_raw = int_returns.popleft()
                    pcap_ret    = usb.parse_one(ret_raw)
                    actual_len  = pcap_ret.payload.get('actuallength', 0) if not pcap_ret.is_encrypted else 0
                    xfr_hex     = pcap_ret.payload.get('transferdata') if not pcap_ret.is_encrypted else None
                    xfr_data    = bytes.fromhex(xfr_hex) if xfr_hex else b''
                    pep_send(sock, usb.build_usb_interrupt_submit_return(
                        seqnum, ep, dirn, actual_len, 0, xfr_data,
                    ))
                else:
                    pep_send(sock, usb.build_usb_interrupt_submit_return(
                        seqnum, ep, dirn, len(idle_report), 0, idle_report,
                    ))

            elif mt == MsgType.USB_BULK_SUBMIT:
                ret_raw = bulk_returns.get(seqnum)
                if ret_raw:
                    pep_send(sock, _patch_seqnum(ret_raw, seqnum))
                else:
                    pep_send(sock, usb.build_usb_bulk_submit_return(
                        seqnum, ep, dirn, 0, 0,
                    ))

            elif mt == MsgType.USB_ISOCHRONOUS_SUBMIT:
                ep_queue = iso_ep_map.get(ep, deque())
                if ep_queue:
                    ret_raw = ep_queue.popleft()
                    pep_send(sock, _patch_seqnum(ret_raw, seqnum))
                else:
                    pep_send(sock, usb.build_usb_isochronous_submit_return(
                        seqnum, ep, dirn,
                        startframe=0, errorcount=0,
                        num_packets=0, iso_packets=[],
                    ))

            elif mt == MsgType.USB_CANCEL_SUBMIT:
                pep_send(sock, usb.build_usb_cancel_submit_return(
                    seqnum, ep, dirn, 0,
                ))

        sock.close()
        print(f"  [sim data {sid:#04x}] closed")


def _patch_seqnum(raw: bytes, new_seqnum: int) -> bytes:
    """Patch the SEQNUM field (first 3 bytes of DATA) in a submit-return message.

    TR-10-14 encodes SEQNUM as the lower 3 bytes of a big-endian 4-byte value:
      data[0..2] = struct.pack('>I', seqnum)[1:]
    Byte data[3] is the endpoint/direction byte and MUST NOT be touched.
    Using struct.pack_into with '>I' would overwrite 4 bytes and corrupt data[3].
    """
    if len(raw) < usb.HEADER_SIZE + 3:
        return raw
    out = bytearray(raw)
    seq3 = struct.pack('>I', new_seqnum & 0xFFFFFF)[1:]  # 3 bytes, big-endian
    out[usb.HEADER_SIZE:usb.HEADER_SIZE + 3] = seq3
    return bytes(out)


# ---------------------------------------------------------------------------
# Control channel + orchestration
# ---------------------------------------------------------------------------

class PcapSenderSim:
    """
    Listens on the control port, exchanges SenderConnectionInfo /
    SenderConnectionStatus, then connects data channels back to the
    Receiver.  Runs until Ctrl-C or the Receiver disconnects.
    """

    def __init__(self, sim: SimSession, ctrl_port: int,
                 psk: Optional[bytes] = None, corrupt_nth: int = 0,
                 pep_params: Optional[PepParams] = None):
        self._sim        = sim
        self._ctrl_port  = ctrl_port
        self._stop       = threading.Event()
        self._psk        = psk
        self._corrupt_nth = corrupt_nth
        self._pep_params = pep_params

    def run(self) -> None:
        srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
        srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
        srv.bind(("0.0.0.0", self._ctrl_port))
        srv.listen(4)
        srv.settimeout(1.0)
        print(f"Listening for Receiver on :{self._ctrl_port}  "
              f"({len(self._sim.session.data_channels)} data channel(s) to replay)")
        print("Press Ctrl-C to stop\n")

        while not self._stop.is_set():
            try:
                conn, addr = srv.accept()
            except socket.timeout:
                continue
            except OSError:
                break

            receiver_ip = addr[0]
            print(f"Receiver connected from {receiver_ip}:{addr[1]}")
            try:
                self._handle_receiver(conn, receiver_ip)
            except Exception as exc:
                print(f"  [sim ctrl] error: {exc}")
            finally:
                try:
                    conn.close()
                except Exception:
                    pass

        srv.close()

    def _handle_receiver(self, conn: socket.socket, receiver_ip: str) -> None:
        sim  = self._sim
        buf  = bytearray()

        # Set up PEP for the control channel (SSID 0 = S2R, 1 = R2S)
        ctrl_pep: Optional[SimPepState] = None
        if self._psk:
            pp = self._pep_params
            kv = int.from_bytes(pp.key_version, 'big') if pp else 1
            biv = pp.iv if pp else 0
            kg = pp.key_generator if pp else b'\x00' * 16
            ctrl_pep = SimPepState(self._psk, sender_kv=kv,
                                   corrupt_nth=self._corrupt_nth,
                                   base_iv=biv, key_generator=kg)
            ctrl_pep.payload_ssid = 0
            ctrl_pep.handshake_done = True  # control channel has no handshake phase

        def ctrl_send(data: bytes) -> None:
            if ctrl_pep:
                data = ctrl_pep.encrypt_s2r(data)
            _sendall(conn, data)

        def ctrl_recv(timeout: float = 15.0):
            msg = _recv_msg(conn, buf, timeout=timeout)
            if msg is _DISCONNECTED or msg is None:
                return msg
            if ctrl_pep and msg.raw:
                dec = bytearray(ctrl_pep.decrypt_r2s(msg.raw))
                dec[0:12] = b'\x00' * 12  # clear CTR/KV so parse_one decodes payload
                return usb.parse_one(bytes(dec))
            return msg

        # Step 1 — send SenderConnectionInfo
        sci = sim.sci_raw
        if not sci:
            print("  [sim ctrl] no SenderConnectionInfo in PCAP!")
            return
        ctrl_send(sci)
        print(f"  [sim ctrl] sent SenderConnectionInfo (encrypted={ctrl_pep is not None})")

        # Step 2 — receive SenderConnectionStatus to learn data port
        msg = ctrl_recv(timeout=15.0)
        if msg is _DISCONNECTED:
            print(f"  [sim ctrl] Receiver disconnected before SenderConnectionStatus")
            return
        if msg is None or msg.msg_type_enum != MsgType.SENDER_CONNECTION_STATUS:
            print(f"  [sim ctrl] expected SCS, got {msg.msg_type_name if msg else 'None'}")
            return

        data_port = msg.payload.get('port', 40000)
        hbeat_idx = msg.payload.get('hbeat', 10)
        print(f"  [sim ctrl] received SenderConnectionStatus  "
              f"data_port={data_port}  hbeat={hbeat_idx}")

        # Per-session stop: shared by all data threads for this connection.
        # Set when this Receiver disconnects so data threads exit too.
        session_stop = threading.Event()

        # Step 3 — spawn data channel connections
        data_threads = []
        for substreamid in sim.session.data_channels:
            data_pep: Optional[SimPepState] = None
            if self._psk:
                pp = self._pep_params
                kv = int.from_bytes(pp.key_version, 'big') if pp else 1
                biv = pp.iv if pp else 0
                kg = pp.key_generator if pp else b'\x00' * 16
                data_pep = SimPepState(self._psk, sender_kv=kv,
                                       corrupt_nth=self._corrupt_nth,
                                       base_iv=biv, key_generator=kg)
            t = threading.Thread(
                target=DataChannelSender(
                    sim, substreamid, receiver_ip, data_port, session_stop,
                    pep_state=data_pep,
                ).run,
                name=f"sim-data-{substreamid:#04x}",
                daemon=True,
            )
            t.start()
            data_threads.append(t)

        # Step 4 — control channel loop: send heartbeats, handle disconnect
        hbeat_period = _heartbeat_period(hbeat_idx)
        last_hbeat   = time.monotonic()
        print(f"  [sim ctrl] heartbeat period ≈ {hbeat_period:.0f} s  — ready "
              f"(Ctrl-C to stop, or reconnect after tester exits)")

        try:
            while not self._stop.is_set():
                if time.monotonic() - last_hbeat >= hbeat_period:
                    ctrl_send(sim.heartbeat_raw)
                    last_hbeat = time.monotonic()
                    print(f"  [sim ctrl] sent HEARTBEAT")

                msg = ctrl_recv(timeout=min(hbeat_period, 1.0))
                if msg is _DISCONNECTED:
                    print(f"  [sim ctrl] Receiver disconnected — waiting for next connection")
                    break
                if msg is None:
                    continue

                mt = msg.msg_type_enum
                if mt == MsgType.VENDOR_SPECIFIC_QUERY:
                    vqtype = msg.payload.get('vqtype', 255) if not msg.is_encrypted else 255
                    cid    = (bytes.fromhex(msg.payload.get('cid', '0050C2'))
                              if not msg.is_encrypted else b'\x00\x50\xC2')
                    ctrl_send(usb.build_vendor_specific_query_return(cid, vqtype, 255))
        finally:
            # Signal data threads to stop and wait briefly for them to wind down.
            session_stop.set()
            for t in data_threads:
                t.join(timeout=2.0)
            print(f"  [sim ctrl] session ended")


