"""
IPMX USB (TR-10-14) PCAP-Driven Sender Simulator.

Reads any IPMX USB PCAP file (generated by generate_usb_test_pcap.py or
usb_pcap_to_ipmx.py) and replays the Sender side of the protocol so that
ipmx_usb_tester.py can connect to it for end-to-end testing without real
hardware.

How it works
------------
1. Parses the PCAP with usbDissector.analyze_pcap to extract Sender and
   Receiver messages for every channel.
2. Listens on the control port.  When a Receiver (tester) connects:
   a. Sends SenderConnectionInfo (from the PCAP).
   b. Receives SenderConnectionStatus → learns the Receiver's data port.
3. Connects to the Receiver's data port for each USB device in the PCAP.
   a. Sends USBStreamInfo.
   b. Receives USBStreamStatus.
4. Main loop — responds to every Submit from the tester:
   - CONTROL_SUBMIT with seqnum N → send the recorded CONTROL_SUBMIT_RETURN
     for seqnum N (matched from the PCAP).  Falls back to a generic SUCCESS
     response if the seqnum is not in the recording.
   - INTERRUPT_SUBMIT → send the next queued INTERRUPT_SUBMIT_RETURN from the
     PCAP (in recording order), cycling back to idle HID reports when exhausted.
   - BULK_SUBMIT / CANCEL_SUBMIT → generic SUCCESS Return.
5. Sends HEARTBEAT messages on the control channel at the negotiated interval.
6. Closes cleanly on Ctrl-C or when the tester disconnects.

Usage
-----
    # In terminal 1 — start the simulator from any IPMX PCAP:
    python3 pcap_sender_sim.py test_pcaps/scenario_12_realistic_typing.pcap

    # In terminal 2 — connect the live tester to it:
    python3 ipmx_usb_tester.py 127.0.0.1 --verbose --duration 30

    # With capture for later analysis:
    python3 ipmx_usb_tester.py 127.0.0.1 --verbose --capture live.pcap

    # Real PCAP sources:
    python3 pcap_sender_sim.py test_pcaps/real_keyboard.pcap
"""

