def main() -> None:
    parser = argparse.ArgumentParser(
        description="IPMX USB TR-10-14 PCAP-driven Sender Simulator",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Replay a synthetic scenario:
  python3 pcap_sender_sim.py test_pcaps/scenario_12_realistic_typing.pcap

  # Replay a converted real capture:
  python3 pcap_sender_sim.py test_pcaps/real_keyboard.pcap

  # Then in another terminal, connect the live tester:
  python3 ipmx_usb_tester.py 127.0.0.1 --verbose --duration 30
  python3 ipmx_usb_tester.py 127.0.0.1 --verbose --capture live_session.pcap
""",
    )
    parser.add_argument(
        'pcap_file',
        help="IPMX USB PCAP file to replay as Sender",
    )
    parser.add_argument(
        '--port', type=int, default=27502,
        metavar='PORT',
        help="Control port to listen on (default: 27502)",
    )
    parser.add_argument(
        '--psk', type=str, default=None,
        metavar='HEX',
        help="Pre-shared key (hex) for PEP encryption (16 or 32 bytes)",
    )
    parser.add_argument(
        '--pep-iv', type=str, default=None, metavar='HEX',
        help="PEP base IV (hex, 16 chars)",
    )
    parser.add_argument(
        '--pep-key-generator', type=str, default=None, metavar='HEX',
        help="PEP key_generator (hex, 32 chars)",
    )
    parser.add_argument(
        '--pep-key-version', type=str, default=None, metavar='HEX',
        help="PEP key_version (hex, 8 chars)",
    )
    parser.add_argument(
        '--corrupt-nth', type=int, default=0,
        metavar='N',
        help="Corrupt every Nth outgoing encrypted S2R message (0 = off)",
    )
    args = parser.parse_args()

    psk_bytes: Optional[bytes] = None
    pep_params: Optional[PepParams] = None
    if args.psk:
        psk_bytes = bytes.fromhex(args.psk)
        if len(psk_bytes) not in (16, 32):
            print("PSK must be 16 or 32 bytes (32 or 64 hex digits)", file=sys.stderr)
            sys.exit(1)
        pep_iv = int(args.pep_iv, 16) if args.pep_iv else 0
        pep_key_gen = bytes.fromhex(args.pep_key_generator) if args.pep_key_generator else b'\x00' * 16
        pep_kv = bytes.fromhex(args.pep_key_version) if args.pep_key_version else b'\x00\x00\x00\x01'
        pep_params = PepParams(
            psk=psk_bytes,
            mode=PepMode.AES_128_CTR_CMAC_64_AAD,
            iv=pep_iv,
            key_generator=pep_key_gen,
            key_version=pep_kv,
        )
        print(f"PEP enabled: PSK={args.psk[:8]}... ({len(psk_bytes)*8}-bit)  "
              f"iv={pep_iv:#018x}  kv={pep_kv.hex()}")

    print(f"Loading PCAP: {args.pcap_file}")
    try:
        sessions = analyze_pcap(args.pcap_file, verbose=False,
                                pep_params=pep_params)
    except SystemExit:
        sys.exit(1)

    if not sessions:
        print("No IPMX sessions found in PCAP", file=sys.stderr)
        sys.exit(1)

    # Use the first session
    session = sessions[0]
    sim     = SimSession(session)

    srv = PcapSenderSim(sim, ctrl_port=args.port, psk=psk_bytes,
                        corrupt_nth=args.corrupt_nth, pep_params=pep_params)

    try:
        srv.run()
    except KeyboardInterrupt:
        print("\nStopped by user")
        srv._stop.set()


if __name__ == '__main__':
    main()
